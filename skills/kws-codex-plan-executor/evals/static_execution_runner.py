#!/usr/bin/env python3
"""Build deterministic execution fixtures through the production v3 runtime."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

SCRIPT_DIR = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPT_DIR))

from cpe_runtime.kernel import Kernel, Transition
from cpe_runtime.manifest import create_manifest, write_manifest
from cpe_runtime.scheduler import run_tasks
from cpe_runtime.worker import Worker


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-") or "fixture"


def content_for(path: str, fixture: dict) -> str:
    spec = str(fixture.get("spec") or "")
    match = re.search(r'exact text\s+"([^"]+)"', spec)
    if match:
        return match.group(1) + "\n"
    if path.endswith("resume-target.md"):
        return "resumed execution from state\n"
    if path.endswith("task-note.md"):
        return "executor task note\n"
    return f"generated by v3 fixture for {path}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", required=True)
    parser.add_argument("--workdir", required=True)
    parser.add_argument("--eval-home", required=True)
    parser.add_argument("--final-output", required=True)
    parser.add_argument("--run-log", required=True)
    args = parser.parse_args()
    fixture = yaml.safe_load(Path(args.fixture).read_text(encoding="utf-8")) or {}
    expected = fixture.get("expected") or {}
    final = Path(args.final_output)
    log = Path(args.run_log)
    final.parent.mkdir(parents=True, exist_ok=True)
    if expected.get("allow_no_state") and expected.get("must_block"):
        final.write_text("Blocked before execution: resolve related dirty scope or missing Files metadata.\n", encoding="utf-8")
        log.write_text('{"type":"turn.completed","status":"blocked"}\n', encoding="utf-8")
        return 0
    repo = Path(args.workdir).resolve()
    eval_home = Path(args.eval_home).resolve()
    run_id = f"{slug(str(fixture.get('name') or 'fixture'))}-v3-{subprocess.check_output(['date', '+%s%N'], text=True).strip()}"
    run_dir = eval_home / ".codex" / "orchestrator" / run_id
    worktree = eval_home / ".codex" / "worktrees" / run_id
    worktree.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "worktree", "add", "-q", "-b", f"codex/{run_id}", str(worktree), "HEAD"], cwd=repo, check=True)
    changed = list(expected.get("files_changed") or [])
    allowed_extra = list(expected.get("allowed_extra_files") or [])
    for path in allowed_extra:
        source = repo / path
        if source.is_file():
            target = worktree / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(source.read_bytes())
    acceptance = str(expected.get("test_after") or " && ".join(f"test -f {path}" for path in changed) or "true")
    task = {"id": "task_0", "title": "fixture", "dependencies": [], "file_claims": changed + allowed_extra, "spec_refs": [], "acceptance_command": acceptance, "prompt": "fixture"}
    pricing = SCRIPT_DIR.parent / "data" / "pricing-snapshot.json"
    manifest = create_manifest(run_id, str(fixture.get("mode", "interactive")), repo, worktree, repo / "plan.md", repo / "spec.md", [task], pricing)
    write_manifest(run_dir / "run_manifest.json", manifest)
    packet = run_dir / "artifacts" / "task-packets" / "task_0.json"
    packet.parent.mkdir(parents=True, exist_ok=True)
    packet.write_text(json.dumps({"schema_version": "3", "task": task}, sort_keys=True) + "\n", encoding="utf-8")
    kernel = Kernel(run_dir)
    kernel.transition(Transition("run.status_changed", {"from": "created", "to": "ready"}))

    def provider(request, _argv):
        if request.attempt_kind == "implementation":
            for path in changed:
                target = worktree / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content_for(path, fixture), encoding="utf-8")
            changed_files = changed
        else:
            changed_files = []
        return {
            "result": {"status": "completed", "summary": request.attempt_kind, "changed_files": changed_files, "findings": [], "evidence_refs": [], "missing_evidence": [], "verification": []},
            "provider_metadata": {"model": "gpt-5.6-sol", "reasoning": "high", "trusted_source": "deterministic_fake_provider"},
            "usage": {"input_tokens": 10, "cached_input_tokens": 2, "output_tokens": 3, "reasoning_output_tokens": 1},
            "events": [{"type": "turn.completed"}],
        }

    result = run_tasks([task], Worker(provider=provider), kernel)
    payload = {"status": "success" if result.get("status") == "completed" else "blocked", "run_id": run_id, "run_dir": str(run_dir), "worktree": str(worktree), **result}
    final.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    log.write_text('{"type":"turn.completed","status":"completed"}\n', encoding="utf-8")
    return 0 if result.get("status") == "completed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
